"""Byte-level BPE with explicit document boundaries and no tokenizer libraries."""

import argparse
import json
import re
from collections import Counter
from pathlib import Path
from typing import Iterable


def pieces(text: str) -> list[str]:
    return re.findall(r"\s+|[^\W\d_]+|\d+|[^\w\s]+|_", text, re.UNICODE)


def merge_pair(ids: tuple[int, ...], pair: tuple[int, int], new_id: int) -> tuple[int, ...]:
    result = []
    i = 0
    while i < len(ids):
        if i + 1 < len(ids) and (ids[i], ids[i + 1]) == pair:
            result.append(new_id)
            i += 2
        else:
            result.append(ids[i])
            i += 1
    return tuple(result)


class ByteBPE:
    eos_id = 256

    def __init__(self, merges: list[tuple[int, int]] | None = None):
        self.merges = [] if merges is None else list(merges)
        self.vocab = {i: bytes([i]) for i in range(256)}
        self.vocab[self.eos_id] = b""
        for new_id, (left, right) in enumerate(self.merges, start=257):
            if left == self.eos_id or right == self.eos_id:
                raise ValueError("EOS cannot participate in a merge")
            self.vocab[new_id] = self.vocab[left] + self.vocab[right]
        self.ranks = {pair: rank for rank, pair in enumerate(self.merges)}

    @property
    def vocab_size(self) -> int:
        return len(self.vocab)

    @classmethod
    def train(cls, documents: Iterable[str], vocab_size: int) -> "ByteBPE":
        if vocab_size < 257:
            raise ValueError("vocab_size must include 256 bytes and EOS")
        words: Counter[tuple[int, ...]] = Counter()
        for document in documents:
            words.update(tuple(piece.encode("utf-8")) for piece in pieces(document))
        if not words:
            raise ValueError("Cannot train tokenizer on empty text")
        merges = []
        for new_id in range(257, vocab_size):
            counts: Counter[tuple[int, int]] = Counter()
            for word, frequency in words.items():
                for pair in zip(word, word[1:]):
                    counts[pair] += frequency
            if not counts:
                break
            pair = min(counts, key=lambda item: (-counts[item], item))
            merges.append(pair)
            updated: Counter[tuple[int, ...]] = Counter()
            for word, frequency in words.items():
                updated[merge_pair(word, pair, new_id)] += frequency
            words = updated
        return cls(merges)

    def encode(self, text: str, *, add_eos: bool = False) -> list[int]:
        result = []
        for piece in pieces(text):
            ids = tuple(piece.encode("utf-8"))
            while len(ids) > 1:
                candidates = [(self.ranks[pair], pair) for pair in zip(ids, ids[1:]) if pair in self.ranks]
                if not candidates:
                    break
                rank, pair = min(candidates)
                ids = merge_pair(ids, pair, 257 + rank)
            result.extend(ids)
        if add_eos:
            result.append(self.eos_id)
        return result

    def decode(self, ids: Iterable[int]) -> str:
        # Arbitrarily generated bytes need not form valid UTF-8; input round trips do.
        return b"".join(self.vocab[token] for token in ids).decode("utf-8", errors="replace")

    def save(self, path: str | Path) -> None:
        Path(path).write_text(
            json.dumps({"version": 1, "pretokenizer": "unicode-runs-v1", "merges": self.merges}),
            encoding="utf-8",
        )

    @classmethod
    def load(cls, path: str | Path) -> "ByteBPE":
        data = json.loads(Path(path).read_text(encoding="utf-8"))
        if data["version"] != 1 or data["pretokenizer"] != "unicode-runs-v1":
            raise ValueError("Unsupported tokenizer format")
        return cls([tuple(pair) for pair in data["merges"]])


def main() -> None:
    parser = argparse.ArgumentParser(description="Train BPE on TRAINING text only")
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--vocab-size", type=int, default=8192)
    parser.add_argument("--max-chars", type=int, default=2_000_000)
    args = parser.parse_args()
    if args.max_chars < 1:
        parser.error("--max-chars must be positive")
    with args.input.open(encoding="utf-8") as source:
        sample = source.read(args.max_chars)
    tokenizer = ByteBPE.train([sample], args.vocab_size)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    tokenizer.save(args.output)
    print(json.dumps({"vocab_size": tokenizer.vocab_size, "sample_chars": len(sample)}))


if __name__ == "__main__":
    main()
